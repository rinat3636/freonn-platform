export interface GeoPage {
  slug: string;
  city: string;
  cityRod: string; // родительный падеж
  cityPred: string; // предложный падеж
  region: string;
  population: string;
  priceCoeff: number; // коэффициент цены относительно базовой
  title: string;
  metaDescription: string;
  h1: string;
  intro: string;
  deliveryDays: string;
  completedProjects: number;
  /** Без поля — гео под ангары (`/angary-*`). */
  kind?: "angary" | "sklad" | "proizvodstvo";
}

const BASE_PRICE_PER_M2 = MO_BASE_RUB_M2;
const PROIZVODSTVO_BASE_PER_M2 = MO_PROIZVODSTVO_BASE_RUB_M2;

function geoSlugKey(page: Pick<GeoPage, "slug">): string {
  return page.slug.replace(/^\/(angary|sklady|proizvodstvennye-zdaniya)-/, "");
}

function isMoscowGeo(page: Pick<GeoPage, "slug" | "city">): boolean {
  return geoSlugKey(page) === "moskva" || page.city === "Москва";
}

/** Числовой ориентир ₽/m² — единый источник для title, meta, FAQ и JSON-LD. */
export function geoRubM2Value(page: GeoPage): number {
  const k = getGeoKind(page);

  if (isMoscowGeo(page)) {
    if (k === "sklad") return MOSCOW_SKLAD_RUB_M2;
    if (k === "proizvodstvo") return MOSCOW_TSEKH_RUB_M2;
    return MOSCOW_ANGAR_RUB_M2;
  }

  if (page.region === "Московская область") {
    return peripheralMoRubM2(
      page.priceCoeff,
      k === "proizvodstvo" ? "proizvodstvo" : k === "sklad" ? "sklad" : "angar",
    );
  }

  const base = k === "proizvodstvo" ? PROIZVODSTVO_BASE_PER_M2 : BASE_PRICE_PER_M2;
  return Math.round(base * page.priceCoeff);
}

/** Ориентир ₽/м² для title и meta (согласован с калькulatorом). */
export function getGeoPricePerM2(page: GeoPage): string {
  return `от ${geoRubM2Value(page).toLocaleString("ru-RU")} ₽/м²`;
}

export function getCityPrice(coeff: number, size = 1000): string {
  const price = Math.round((BASE_PRICE_PER_M2 * coeff * size) / 1000) * 1000;
  return `от ${price.toLocaleString("ru-RU")} ₽`;
}

/** Ориентир стоимости объекта для гео-страницы. */
export function getGeoPriceHint(page: GeoPage, size = 1000): string {
  const price = Math.round((geoRubM2Value(page) * size) / 1000) * 1000;
  return `от ${price.toLocaleString("ru-RU")} ₽`;
}

/** Синхронизирует title/meta angary-страниц с `geoRubM2Value`. */
export function syncAngaryGeoSeo(page: GeoPage): GeoPage {
  const p: GeoPage = { ...page, kind: page.kind ?? "angary" };
  const perM2 = getGeoPricePerM2(p);
  const deliveryStart = p.deliveryDays.split("–")[0]?.trim() || "20";

  if (p.city === "Москва") {
    return {
      ...p,
      title: `Строительство ангаров в Москве под ключ — ${perM2} | Freonn`,
      metaDescription: `Строительство ангаров в Москве под ключ ${perM2}. 87+ объектов в регионе, монтаж от ${deliveryStart} дней. Офис на Варшавском шоссе. 8(800)101-2009`,
    };
  }

  return {
    ...p,
    title: `Строительство ангаров в ${p.cityPred} под ключ — ${perM2} | Freonn`,
    metaDescription: `Ангары в ${p.cityPred} ${perM2}. Под ключ: проект, фундамент, монтаж от ${deliveryStart} дней. Расчёт за 1 день. 8(800)101-2009`,
  };
}

export type GeoKindResolved = "angary" | "sklad" | "proizvodstvo";

export function getGeoKind(page: GeoPage): GeoKindResolved {
  return page.kind ?? "angary";
}

/** Хаб для крошек и ссылок: ангары / склады / производство. */
export function getGeoHub(page: GeoPage): { href: string; name: string } {
  const k = getGeoKind(page);
  if (k === "sklad") return { href: "/sklady", name: "Склады" };
  if (k === "proizvodstvo") return { href: "/proizvodstvennye-zdaniya", name: "Производственные здания" };
  return { href: "/angary", name: "Ангары" };
}

export function getGeoLocalBusinessName(page: GeoPage): string {
  const k = getGeoKind(page);
  const kindRu = k === "sklad" ? "склады" : k === "proizvodstvo" ? "производственные здания" : "ангары";
  return `Freonn — ${kindRu} в ${page.cityRod}`;
}

export function getGeoSchemaOfferDescription(page: GeoPage): string {
  const k = getGeoKind(page);
  const ph = getGeoPriceHint(page);
  if (k === "sklad") return `Строительство складов в ${page.cityPred} под ключ — ${ph} за объект 1 000 м²`;
  if (k === "proizvodstvo") return `Производственные здания в ${page.cityPred} под ключ — ${ph} за объект 1 000 м²`;
  return `Строительство ангаров в ${page.cityPred} под ключ — ${ph} за объект 1 000 м²`;
}

