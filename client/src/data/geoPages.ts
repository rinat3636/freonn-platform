function skladGeoFromAngary(a: GeoPage): GeoPage {
  const key = a.slug.replace("/angary-", "");
  const page: GeoPage = { ...a, kind: "sklad", slug: `/sklady-${key}` };
  const perM2 = getGeoPricePerM2(page);
  const tier1 = (MO_TIER1_SLUG_KEYS as readonly string[]).includes(key);
  const hook = moTier1SkladHook(key);
  const intro = tier1 && hook
    ? `Склады в ${a.cityPred}: ${hook} Freonn — ${perM2}, монтаж от ${a.deliveryDays.split("–")[0]} дней.`
    : tier1
      ? `Склады в ${a.cityPred}: логистические терминалы, fulfilment и класс B. ${a.intro} Freonn — ${perM2}, монтаж от ${a.deliveryDays.split("–")[0]} дней.`
      : `Freonn проектирует и строит склады в ${a.cityPred} и ${a.region}: нетемпературные и температурные комплексы, логистические терминалы. Собственное производство металлоконструкций, цена в договоре, монтажные бригады в регионе.`;
  return {
    ...page,
    h1: `Строительство складов в ${a.cityPred} под ключ`,
    title: `Склады в ${a.cityPred} под ключ — ${perM2} | Freonn`,
    metaDescription: `Склады в ${a.cityPred} под ключ ${perM2}. Проект, производство МК, монтаж. 500+ объектов с 2011 года. 8(800)101-2009`,
    intro,
  };
}

